import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';

const html=readFileSync('index.html','utf8');
const inline=html.match(/<script>\s*([\s\S]*?)<\/script>/)?.[1];
assert.ok(inline,'tracker inline script found');
const dom=new JSDOM(html,{url:'https://joshuamaziarz1-ux.github.io/-jacks-flight-tracker/',runScripts:'outside-only'});
const w=dom.window;
w.HTMLElement.prototype.scrollIntoView=()=>{};
let fetchCalls=0, intervalCalls=0, clearedIntervals=0, removedLayers=0;
w.fetch=async()=>{
 fetchCalls++;
 return {ok:true,json:async()=>({ac:[]})};
};
w.setInterval=()=>{intervalCalls++;return intervalCalls};
w.clearInterval=()=>{clearedIntervals++};
const map={setView(){return this},whenReady(cb){cb()},invalidateSize(){},removeLayer(){removedLayers++},panTo(){},changeStyle(){}};
function layer(){return {addTo(){return this},on(){return this},redraw(){},setUrl(){}}}
w.L={map:()=>map,tileLayer:()=>layer(),marker:()=>layer(),polyline:()=>layer(),divIcon:()=>({})};
// Both scripts share one page's lexical environment in a browser.
w.eval(inline+'\n'+readFileSync('saved-aircraft.js','utf8'));
const id=name=>w.document.getElementById(name);
assert.equal(fetchCalls,0,'opening page makes zero aircraft requests');
assert.equal(intervalCalls,0,'opening page starts no polling timers');
assert.equal(id('refreshPlaneBtn').disabled,true);
assert.equal(id('stopTrackingBtn').disabled,true);
assert.equal(id('autoRefreshToggle').checked,false);
assert.equal(id('tailDisplay').textContent,'—','no default selected aircraft');
assert.ok(id('statusText').textContent.includes('Select'));
assert.ok(id('libraryPlanes').textContent.includes('N233ND'));
assert.ok(id('libraryPlanes').textContent.includes('N278DC'));
assert.equal(id('mapStyleBtn').textContent,'Map: Dark ▾');
id('mapStyleBtn').click();
assert.equal(id('mapStyleBtn').textContent,'Map: Streets ▾');
assert.equal(removedLayers,0,'vector map changes style without removing markers');
const track=Array.from(id('libraryPlanes').querySelectorAll('button')).find(b=>b.textContent==='Track');
assert.ok(track,'saved airplane has a Track button');
track.click();
await new Promise(resolve=>setTimeout(resolve,30));
assert.ok(fetchCalls>=1&&fetchCalls<=3,'explicit Track makes a one-time lookup through available sources');
const requestsAfterTrack=fetchCalls;
assert.equal(intervalCalls,0,'one-time track does not begin automatic refresh');
assert.equal(id('stopTrackingBtn').disabled,false);
id('autoRefreshToggle').checked=true;
id('autoRefreshToggle').dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(intervalCalls,1,'enabling auto-refresh creates exactly one selected-aircraft interval');
id('stopTrackingBtn').click();
assert.equal(id('tailDisplay').textContent,'—');
assert.equal(id('stopTrackingBtn').disabled,true);
assert.ok(clearedIntervals>0,'stop cancels selected-aircraft polling');
assert.equal(id('autoRefreshToggle').checked,false,'stopping tracking turns auto-refresh off');
assert.equal(fetchCalls,requestsAfterTrack,'stop does not issue a new request');
console.log('PASS: no automatic saved-plane search on launch; manual Track only; opt-in refresh and Stop; map style changes');
